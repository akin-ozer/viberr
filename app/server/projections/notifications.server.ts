/**
 * Per-user notification rows (orchestrator ruling 9): SQLite-owned,
 * sorted by real timestamp DESC, task/project soft refs (cross-project
 * capable — the seed's DEP-31/BIL-9 rows point at the stub projects).
 * Read state is monotonic (no mark-unread) and idempotent.
 */

export interface CreateNotificationInput {
  /** Deterministic id for idempotent seeding; autogenerated when omitted. */
  id?: string;
  userId: string;
  kind: NotificationKind;
  ptype?: "input" | "blocked" | null;
  title?: string | null;
  text: string;
  from?: ActorRender | null;
  projectSlug?: string | null;
  taskKey?: string | null;
  occurredAt?: string;
  readAt?: string | null;
  /** Skip the recipient's routing-pref filter. For FIXTURE inserts (the demo
   *  seed) only — a fixture must be deterministic and not vary with whatever
   *  prefs a prior session left, or `seed --reset` stops being pristine. */
  bypassPrefs?: boolean;
}

/**
 * Insert a per-user notification — UNLESS the recipient has silenced its
 * routing category (FR26 / profile notification routing). This is the single
 * insert point every creation path funnels through (task watcher fan-out,
 * @mention, policy engine, seed), so gating here is what makes the profile
 * toggles govern real delivery instead of being decorative. Opt-out model: a
 * user with no stored pref receives everything (default ON), and a prefs-read
 * failure defaults to delivering — a routing lookup must never silently drop a
 * governance notification. Returns the row id, or null when the category was
 * off and nothing was written.
 */
export function createNotification(
  db: DatabaseSync,
  input: CreateNotificationInput,
): string | null {
  let deliver = true;
  if (!input.bypassPrefs) {
    try {
      deliver = isNotifKindEnabled(db, input.userId, input.kind);
    } catch {
      deliver = true; // never drop a notification on a prefs-lookup error
    }
  }
  if (!deliver) return null;

  const id = input.id ?? newId("ntf");
  const now = new Date().toISOString();
  db.prepare(
    `INSERT OR REPLACE INTO notifications
       (id, user_id, kind, ptype, title, text, actor_json, project_slug,
        task_key, occurred_at, read_at, created_at)
     VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)`,
  ).run(
    id,
    input.userId,
    input.kind,
    input.ptype ?? null,
    input.title ?? null,
    input.text,
    input.from ? JSON.stringify(input.from) : null,
    input.projectSlug ?? null,
    input.taskKey ?? null,
    input.occurredAt ?? now,
    input.readAt ?? null,
    now,
  );
  emitProjectionEvent({
    type: "notification.created",
    userId: input.userId,
    occurredAt: input.occurredAt ?? now,
  });
  return id;
}

/**
 * B-FD6: where a notification row actually goes when clicked. The inbox routed
 * only rows carrying BOTH a project and a task, so an org- or project-level row
 * (a policy notification, a project-scoped quality alert) rendered exactly like
 * a clickable one and did nothing — a dead click with no explanation. Resolving
 * the destination here, once, lets every surface either navigate or render the
 * row as plainly non-clickable instead of each one re-deriving the rule.
 */
export function notificationHref(
  record: Pick<NotificationRecord, "projectSlug" | "taskKey">,
): string | null {
  if (record.projectSlug && record.taskKey) {
    return `/projects/${record.projectSlug}/tasks/${record.taskKey}`;
  }
  // A project-scoped row still has a surface it concerns: that project's board.
  if (record.projectSlug) return `/projects/${record.projectSlug}`;
  // Org-wide rows (no project ref) concern no single page — never clickable.
  return null;
}

export interface NotificationListItem extends NotificationRecord {
  /** Resolved destination, or null when this row concerns no navigable
   *  surface — the signal a renderer uses to style it as non-clickable. */
  href: string | null;
  /**
   * F18-1: the row names a project (projectSlug set) that no longer exists in
   * the store — e.g. the project was deleted after the notification was written.
   * Its `href` is nulled (clicking it 404'd on a shell-less error page), the
   * renderer shows a "no longer exists" note, and it is dropped from the unread
   * badge (`countUnreadNotifications`) so a wiped project stops inflating it.
   */
  targetMissing: boolean;
}

/**
 * E6: ONE reading of "waiting on you", shared by the two surfaces that answer
 * that question — this inbox and Home's project cards. They each used to pick
 * their own bucket out of `decisionsRequiring`, which is a comment-deep
 * agreement: nothing failed if one of them started counting the other bucket.
 *
 * The reading: a decision waits on YOU iff it is in `mine`. The org-admin
 * `overrideEligible` bucket is deliberately NOT folded in — the D2 override is
 * governance reach into a project the admin holds no acting role in, not a
 * personal to-do, and folding it in would tell an org admin they personally owe
 * an answer on every project in the instance. It is not dropped either: Home
 * carries it as its own `overrideWaiting` counter, under its own label, so the
 * reach stays visible without inflating the inbox number. The notifications
 * list has no second counter because it has no row to hang one on — a
 * notification exists only for someone who was actually notified.
 */
export interface DecisionInboxIndex {
  /** `${projectSlug}::${taskKey}` for every decision waiting on this user. */
  waitingOnYou: Set<string>;
  /** projectSlug → how many decisions wait on this user there. */
  waitingBySlug: Map<string, number>;
  /** projectSlug → how many are reachable ONLY through the org-admin override. */
  overrideBySlug: Map<string, number>;
}

export function indexDecisionInbox(
  db: DatabaseSync,
  userId: string,
): DecisionInboxIndex {
  const decisions = decisionsRequiring(db, userId);
  const waitingOnYou = new Set<string>();
  const waitingBySlug = new Map<string, number>();
  for (const d of decisions.mine) {
    waitingOnYou.add(`${d.projectSlug}::${d.taskKey}`);
    waitingBySlug.set(d.projectSlug, (waitingBySlug.get(d.projectSlug) ?? 0) + 1);
  }
  const overrideBySlug = new Map<string, number>();
  for (const d of decisions.overrideEligible) {
    overrideBySlug.set(
      d.projectSlug,
      (overrideBySlug.get(d.projectSlug) ?? 0) + 1,
    );
  }
  return { waitingOnYou, waitingBySlug, overrideBySlug };
}

/** Newest-first by real timestamp (deliberate divergence from the mock's
 * splice order — ruling 9). Joins project display names where resolvable,
 * plus the LIVE task decision state (F7-NOTIF1): packet/approval rows are
 * reconciled against task_projections at read time — same-database join,
 * no per-mutation notification writes — so `waitingOnYou` reflects whether
 * the decision is actually still open. Home's per-project decisions counter
 * (home-query.server.ts) applies the same open-packet/pending-rec +
 * non-terminal-stage rule; keep them in step. */
export function listNotifications(
  db: DatabaseSync,
  userId: string,
  options: { limit?: number } = {},
): NotificationListItem[] {
  // SAFETY: `n.*` is the `notifications` table, whose columns are
  // NotificationRow's required fields one-for-one with the same nullability
  // (`kind` pinned by its CHECK constraint to NOTIFICATION_KINDS, `ptype` to
  // input|blocked). The five joined columns are exactly NotificationRow's
  // OPTIONAL fields, which the LEFT JOINs leave null when unmatched.
  const rows = db
    .prepare(
      `SELECT n.*, p.name AS project_name, p.stages_json AS project_stages_json,
              t.stage AS task_stage,
              (t.packet_json IS NOT NULL AND t.packet_json <> '') AS task_has_packet,
              t.recommendation_count AS task_recommendation_count
       FROM notifications n
       LEFT JOIN projects p ON p.slug = n.project_slug
       LEFT JOIN task_projections t
         ON t.project_slug = n.project_slug AND t.task_key = n.task_key
       WHERE n.user_id = ?
       ORDER BY n.occurred_at DESC, n.id DESC
       LIMIT ?`,
    )
    .all(userId, options.limit ?? 100) as NotificationRow[];
  // E1: `from` actors are baked at creation — overlay the current
  // users-table identity so renames reflect in the inbox immediately.
  const overlay = createActorRenderOverlay(db);
  // R8-3: "Waiting on you" is member-scoped — a decision notification waits on
  // THIS user only if its task is in the user's actionable decision set
  // (maintainer+ / task-owner, and NOT the org-admin override). This subsumes
  // the old live-decision check AND drops decisions the viewer can't act on
  // (non-member inflation) and superseded packets (the set keys off live task
  // state, one decision per task). E6: the bucket choice is `indexDecisionInbox`
  // above, which Home reads too — not a local pick out of `decisionsRequiring`.
  const { waitingOnYou: mine } = indexDecisionInbox(db, userId);
  return rows.map((row) => {
    const record = mapNotificationRow(row);
    // F18-1: the LEFT JOIN yields a null project name only when no projects row
    // matches the slug — i.e. the project this row points at is gone. Such a row
    // has no live surface to open (its board/task 404s), so it is not clickable
    // and the renderer flags it as orphaned. (A null project_slug is an org-wide
    // row, not an orphan.)
    const targetMissing = record.projectSlug != null && row.project_name == null;
    const scoped: NotificationListItem = {
      ...record,
      waitingOnYou:
        (record.kind === "packet" || record.kind === "approval") &&
        record.projectSlug != null &&
        record.taskKey != null &&
        mine.has(`${record.projectSlug}::${record.taskKey}`),
      href: targetMissing ? null : notificationHref(record),
      targetMissing,
    };
    return scoped.from ? { ...scoped, from: overlay(scoped.from) } : scoped;
  });
}

/**
 * Drop every notification that pointed into a project (C01-A12, pass 32 —
 * the project-delete action used to run this DELETE inline, the one write to
 * this table outside the module that owns it). Notifications are app-owned
 * (no FK cascade to projects), so a deleted project would otherwise leave
 * orphaned "waiting on you" rows that dead-end on a 404 when opened (F2).
 */
export function deleteProjectNotifications(db: DatabaseSync, projectSlug: string): number {
  return Number(
    db.prepare(`DELETE FROM notifications WHERE project_slug = ?`).run(projectSlug).changes,
  );
}

/** One person's notifications for one project — what a member REMOVAL leaves
 *  behind. `deleteProjectNotifications` covers the project going away, and
 *  `countUnreadNotifications` already discounts rows whose project is gone; a
 *  removed member is the third case, and the only one where the project still
 *  EXISTS, so their rows kept rendering and kept counting while every click
 *  dead-ended on a project they can no longer reach. */
export function deleteMemberProjectNotifications(
  db: DatabaseSync,
  projectSlug: string,
  userId: string,
): number {
  return Number(
    db
      .prepare(
        `DELETE FROM notifications WHERE project_slug = ? AND user_id = ?`,
      )
      .run(projectSlug, userId).changes,
  );
}

export function countUnreadNotifications(
  db: DatabaseSync,
  userId: string,
): number {
  // F18-1: an unread row that points at a DELETED project is not actionable —
  // clicking it 404s — so it must not inflate the bell badge. Count unread rows
  // that are either org-wide (no project_slug) or whose project still exists.
  // SAFETY: an un-grouped `count(*)` always returns exactly one row holding one
  // INTEGER column, so `.get()` is never undefined and `c` is always a number.
  const row = db
    .prepare(
      `SELECT count(*) AS c
       FROM notifications n
       LEFT JOIN projects p ON p.slug = n.project_slug
       WHERE n.user_id = ? AND n.read_at IS NULL
         AND (n.project_slug IS NULL OR p.slug IS NOT NULL)`,
    )
    .get(userId) as { c: number };
  return row.c;
}

/** Targeted `notification.read` — other tabs of the same user revalidate so
 * their bell badge drops (E12: mark-read used to emit nothing). */
function emitNotificationRead(userId: string): void {
  emitProjectionEvent({
    type: "notification.read",
    userId,
    occurredAt: new Date().toISOString(),
  });
}

/** Idempotent read-marking (monotonic; re-marking is a no-op). */
export function markNotificationsRead(
  db: DatabaseSync,
  userId: string,
  ids: string[],
): number {
  if (ids.length === 0) return 0;
  const placeholders = ids.map(() => "?").join(", ");
  const result = db
    .prepare(
      `UPDATE notifications SET read_at = ?
       WHERE user_id = ? AND read_at IS NULL AND id IN (${placeholders})`,
    )
    .run(new Date().toISOString(), userId, ...ids);
  const changes = Number(result.changes);
  if (changes > 0) emitNotificationRead(userId);
  return changes;
}

export function markAllNotificationsRead(
  db: DatabaseSync,
  userId: string,
): number {
  const result = db
    .prepare(
      `UPDATE notifications SET read_at = ? WHERE user_id = ? AND read_at IS NULL`,
    )
    .run(new Date().toISOString(), userId);
  const changes = Number(result.changes);
  if (changes > 0) emitNotificationRead(userId);
  return changes;
}

/**
 * Packet/approval resolution side-effect (contracts §1.2): marks that
 * task's packet + approval notifications read for EVERY user, idempotently.
 * Emits `notification.read` per affected user (their badges drop live).
 */
export function markTaskPacketApprovalRead(
  db: DatabaseSync,
  projectSlug: string,
  taskKey: string,
  kinds: NotificationKind[] = ["packet", "approval"],
): number {
  if (kinds.length === 0) return 0;
  const placeholders = kinds.map(() => "?").join(", ");
  // Affected users FIRST (the bulk UPDATE loses them) — one event each.
  // SAFETY: the single selected column is `notifications.user_id`, TEXT NOT
  // NULL (0001_baseline.sql).
  const affected = db
    .prepare(
      `SELECT DISTINCT user_id FROM notifications
       WHERE project_slug = ? AND task_key = ? AND read_at IS NULL
         AND kind IN (${placeholders})`,
    )
    .all(projectSlug, taskKey, ...kinds) as { user_id: string }[];
  const result = db
    .prepare(
      `UPDATE notifications SET read_at = ?
       WHERE project_slug = ? AND task_key = ? AND read_at IS NULL
         AND kind IN (${placeholders})`,
    )
    .run(new Date().toISOString(), projectSlug, taskKey, ...kinds);
  const changes = Number(result.changes);
  if (changes > 0) {
    for (const row of affected) emitNotificationRead(row.user_id);
  }
  return changes;
}

/**
 * F20-11: is this request a GENUINE top-level view of the task page — the one
 * moment R19-15's "opening the task IS seeing its notifications" actually holds
 * — as opposed to a background revalidation?
 *
 * The R19-15 loader used to mark-seen on EVERY run, justified by "this loader
 * runs only on a real view". That premise was wrong: React Router 8 single
 * fetch addresses every client-side data load to the `.data` wire URL
 * (`/projects/<slug>/tasks/<key>.data?_routes=…`) — the SSE revalidation that
 * fires on every task change, the revalidation after a POST on this page, and a
 * client-side link navigation, ALL of them. So a task parked in a background
 * tab silently consumed any notification that arrived for it within
 * milliseconds, and the bell never badged (it swallowed four "Blocked —
 * decision needed" packets in the live repro).
 *
 * Only a real top-level document load (typing the URL, a hard refresh,
 * open-in-new-tab) arrives on the clean route path — never the `.data` wire
 * address — and the browser stamps it `Sec-Fetch-Mode: navigate`. So the rule
 * is: mark-seen iff the path is NOT the single-fetch `.data` address (the same
 * framework signal `require-user.server.ts` keys off) and, when the browser
 * sends `Sec-Fetch-Mode`, it says `navigate`.
 *
 * We deliberately do NOT mark on a client-side `.data` navigation: server-side
 * it is indistinguishable from the background revalidation that caused F20-11,
 * and erring toward an un-cleared bell (it over-counts a task you are looking
 * at) is the SAFE direction — the old code erred toward silently eating an
 * unseen governance packet. The bell popover already marks a row read on click
 * (`top-bell.tsx`), so opening a task FROM a notification still clears it, and a
 * full load / "Mark all read" clears the rest.
 */
export function isTaskViewNavigation(request: Request): boolean {
  // Single-fetch data requests carry the `.data` suffix; a genuine SSR document
  // load lands on the clean route path. This alone excludes every revalidation.
  if (new URL(request.url).pathname.endsWith(".data")) return false;
  // When the browser sends it, a top-level navigation is `Sec-Fetch-Mode:
  // navigate` (any other same-origin fetch that reached a clean path is not);
  // absent (tests / non-browser SSR) we rely on the `.data` signal above.
  const mode = request.headers.get("Sec-Fetch-Mode");
  return mode === null || mode === "navigate";
}

/**
 * R19-15: per-user VIEW side-effect — opening a task's page marks THIS
 * viewer's unread notifications for that (project, task) read, EVERY kind.
 * This is what lets the bell badge count genuinely-unseen items: a user who
 * reaches the task from the board (never touching the popover or the inbox)
 * must not keep its rows unread forever. Deliberately unlike
 * `markTaskPacketApprovalRead` above, which is a RESOLUTION side-effect:
 * resolving a decision clears the packet/approval kinds for EVERY user
 * because the decision itself is gone, while a view proves only that ONE
 * user has seen — so this touches one user's rows and leaves everyone
 * else's unread. Same monotonic/idempotent contract, same single
 * `notification.read` emit only when something actually changed.
 */
export function markTaskNotificationsSeen(
  db: DatabaseSync,
  userId: string,
  projectSlug: string,
  taskKey: string,
): number {
  const result = db
    .prepare(
      `UPDATE notifications SET read_at = ?
       WHERE user_id = ? AND project_slug = ? AND task_key = ?
         AND read_at IS NULL`,
    )
    .run(new Date().toISOString(), userId, projectSlug, taskKey);
  const changes = Number(result.changes);
  if (changes > 0) emitNotificationRead(userId);
  return changes;
}
